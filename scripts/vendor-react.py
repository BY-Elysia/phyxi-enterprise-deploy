#!/usr/bin/env python3
"""Refresh the pinned, browser-ready React asset using upstream npm distributions."""
import base64
import gzip
import hashlib
import io
from pathlib import Path
import re
import subprocess
import tarfile

OUTPUT = Path(__file__).resolve().parents[1] / "console/web/ui/vendor"
REACT_VERSION = "19.3.1"
PACKAGES = {
    "react": (REACT_VERSION, "QNhWdt7nrgVWWQG58QuGsAR3jv3Hbe4mb4vz7w2csnHavciZJgda1CPNaldF6eVxv90ud3jUXpKlHL69gO38yw==", {
        "react": "react.production.js",
    }),
    "react-dom": (REACT_VERSION, "Y0bARz53lhEC1NMCASs0/j+faB/zqt3R8hpvg1e8+61ZVJ4UL0UdC4cBbXfZMcIuhrfgeILTLe+ZeBCavQPtKQ==", {
        "react-dom": "react-dom.production.js",
        "react-dom/client": "react-dom-client.production.js",
    }),
    "scheduler": ("0.28.0", "juorfCmIkIw8tT+p5BXSm6PJjQF/ycEYmKyzURCIt/RaZIhL+PulbQ9Yu2z1HdOJDdqDTlxA1+xKBmHXJsczAw==", {
        "scheduler": "scheduler.production.js",
    }),
}


def distributions():
    sources = {}
    licenses = []
    for name, (version, integrity, modules) in PACKAGES.items():
        url = f"https://registry.npmjs.org/{name}/-/{name}-{version}.tgz"
        archive = subprocess.check_output(["curl", "--fail", "--silent", "--show-error", "--max-time", "30", url])
        digest = base64.b64encode(hashlib.sha512(archive).digest()).decode()
        if digest != integrity:
            raise ValueError(f"{name} distribution failed SHA-512 verification")
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            licenses.append(f"{name} {version}\n" + tar.extractfile("package/LICENSE").read().decode().strip())
            for module, filename in modules.items():
                sources[module] = tar.extractfile(f"package/cjs/{filename}").read().decode().strip()
    known = set(sources)
    for module, source in sources.items():
        dependencies = set(re.findall(r'''require\(["']([^"']+)["']\)''', source))
        if not dependencies <= known or "process.env" in source:
            raise ValueError(f"{module} requires additional browser adaptation: {dependencies - known}")
    return sources, licenses


def main():
    sources, licenses = distributions()
    factories = [
        f'  "{module}": (module, exports, require) => {{\n{source}\n  }}'
        for module, source in sources.items()
    ]
    browser_module = """// Generated by scripts/vendor-react.py from the pinned npm production distributions.
const factories = {
""" + ",\n".join(factories) + """
};
const modules = new Map();
function require(name) {
  if (modules.has(name)) return modules.get(name).exports;
  const factory = factories[name];
  if (!factory) throw new Error("Unknown React dependency: " + name);
  const module = { exports: {} };
  modules.set(name, module);
  factory(module, module.exports, require);
  return module.exports;
}
export const React = require("react");
export const { createRoot } = require("react-dom/client");
"""
    (OUTPUT / f"react-{REACT_VERSION}.js").write_text(browser_module)
    with (OUTPUT / f"react-{REACT_VERSION}.js.gz").open("wb") as output:
        with gzip.GzipFile(filename="", mode="wb", fileobj=output, mtime=0, compresslevel=9) as compressed:
            compressed.write(browser_module.encode())
    (OUTPUT / "LICENSES.txt").write_text("\n\n".join(licenses) + "\n")


if __name__ == "__main__":
    main()
